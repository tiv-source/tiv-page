package de.tivsource.page.common.simple;

/**
 * @author Marc Michele
 *
 */
public class SimpleBooleanType {

    private String name;

    private Boolean value;

    /**
     * @return the name
     */
    public String getName() {
        return name;
    }

    /**
     * @param name the name to set
     */
    public void setName(String name) {
        this.name = name;
    }

    /**
     * @return the value
     */
    public Boolean getValue() {
        return value;
    }

    /**
     * @param value the value to set
     */
    public void setValue(Boolean value) {
        this.value = value;
    } 

}// Ende class
